"""Build the enhanced game: the scroller module and the patched main program for both
builds (512K and 1MB), and the disk images.

  cd enhanced/tools
  VASM=/path/to/vasmm68k_mot python3 build_enh.py [--raster]

Writes enhanced/build/:
  512k/  main.bin, module.bin (and the generated symbol files, listings)
  1mb/   main.bin, module.bin
  gng_enhanced.adf       both enhanced programs and the original bootblock, which picks one by
                         the memory it finds (1MB of chip RAM, or memory above 512K: the 1MB
                         program; otherwise the 512K one) - as the original disk
  gng_enhanced_512k.adf  the 512K program only: the bootblock is changed (two instructions) to
                         load it whatever the memory
The 512K program draws every frame, as the 1MB one does (src/fps50_patches.s: the original
draws only on even frames, a fixed 25 fps); when a frame's work does not fit, the game skips
the next logic step and drops to 25 fps by itself.
--fps25: the 512K program as the original, drawing on even frames only, on a 512K-only disk:
gng_enhanced_512k_25hz.adf (with --raster too: gng_enhanced_512k_25hz_raster.adf), to compare
--raster: the timing build (outputs *_raster): the background colour shows which part of each
frame is running (src/raster_patches.s, RASTER in src/module.s)

For each build:
 1. assemble the original source (checked against its original binary) with a listing, and
    turn its labels into orig_syms.i (plus the few names patches.s needs: StartLoad,
    PrintField, PrintBody);
 2. assemble src/module.s at its load address -> module.bin (BUILD_1MB for the 1MB build); its
    Enh* entry points -> module_syms.i;
 3. assemble each block of src/patches.s on its own at its address, check that it fits the
    space it replaces, and write it into a copy of the original program.
Then tools/disk/mkdisk.py makes the images, with the modules added on their own tracks, and
each image is decoded again to check it."""
import hashlib, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ENH = os.path.join(HERE, '..')
ROOT = os.path.join(ENH, '..', 'original')  # the original game's folder (original/: its sources, tools, files)
SRC, OUT = os.path.join(ENH, 'src'), os.path.join(ENH, 'build')
VASM = os.environ.get('VASM', 'vasmm68k_mot')
BOOT_SHA1 = '0bf93a4078bf317fa2774b4b973e1c79c0060227'
BUILDS = {
    '512k': dict(src='gng_main.s', equates='gng_equates.i', sha1='2628a93c164a5a8791272c146053b0afb3ddcf14',
                 load=0x80,            # labels are addresses; the file starts at $80
                 track=110, module_track=132, defs=(),
                 names={'StartLoad': 0x5D32, 'StartLoadEnd': 0x5D3A, 'PrintField': 'l_0B0D6', 'PrintBody': 'l_0B0E2',
                        'CreditsCall': 0x5EF0, 'CreditsCallEnd': 0x5EF4,
                        'Level1LogicEnd': 0x5EBE, 'LogicExitEnd': 0x6BF8,
                        'PlayFrameExit': 0x71E6, 'PlayFrameExitEnd': 0x71EC}),
    '1mb': dict(src='gng_main.s', equates='gng_equates.i', sha1='e44347679297d5d864ae7b0da689714970e261ad',
                load=0,                # assembled at org 0: labels are file offsets
                track=17, module_track=133, defs=(('BUILD_1MB', 1),),
                names={'StartLoad': 0x5D88, 'StartLoadEnd': 0x5D90, 'PrintField': 'l_0B0D6', 'PrintBody': 'l_0B0E2',
                       'CreditsCall': 0x5F46, 'CreditsCallEnd': 0x5F4A,
                       'Level1LogicEnd': 0x5F14, 'LogicExitEnd': 0x6C56,
                       'PlayFrameExit': 0x724E, 'PlayFrameExitEnd': 0x7254}),
}


def vasm(src, out, listing=None, defs=(), opt=False, inc=OUT):
    cmd = [VASM, '-Fbin', '-m68000', '-quiet', '-I', inc, '-I', SRC, '-I', ROOT, '-o', out]
    if not opt: cmd.append('-no-opt')
    if listing: cmd += ['-L', listing]
    cmd += [f'-D{k}={v}' for k, v in defs] + [src]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        sys.exit(f'vasm {os.path.basename(src)}:\n{r.stdout}{r.stderr}')


def symbols(listing, keep=lambda n: True):
    """name -> address of the labels in a vasm listing"""
    out = {}
    text = open(listing).read()
    part = text[text.index('Symbols by name:'):text.index('Symbols by value:')]
    for m in re.finditer(r'^(\S+)\s+A:([0-9A-F]+)$', part, re.M):
        if keep(m.group(1)): out[m.group(1)] = int(m.group(2), 16)
    return out


def write_syms(path, syms):
    with open(path, 'w') as f:
        f.write('; generated by build_enh.py\n')
        for k, v in sorted(syms.items()):
            f.write(f'{k}\tequ\t${v:X}\n')


def patch_blocks(path):
    """(preamble, [(start, end, text)]) from a patch file: the text before the first block
    (equates only) is put in front of every block"""
    pre, blocks, cur = [], [], None
    for line in open(path):
        m = re.match(r';@patch\s+(\S+)\s+(\S+)', line)
        if m:
            cur = [m.group(1), m.group(2), []]; blocks.append(cur)
        elif cur: cur[2].append(line)
        else: pre.append(line)
    return ''.join(pre), [(a, b, ''.join(t)) for a, b, t in blocks]


def apply_patches(prog, path, load, header, known, out, tag):
    """assemble each block of a patch file at its address and write it into prog (a bytearray
    holding the program as loaded at 'load'); header: assembler lines in front of each block;
    known: the symbols already defined (block labels are collected after them)"""
    pre, blocks = patch_blocks(path)
    addr = lambda tok: int(tok[1:], 16) if tok.startswith('$') else known[tok]
    tmp_s, tmp_b, tmp_l = (os.path.join(out, 'patch.' + e) for e in ('s', 'bin', 'lst'))
    psyms = {}
    for a, b, body in blocks:
        write_syms(os.path.join(out, 'patch_syms.i'), psyms)
        start, end = addr(a), addr(b)
        with open(tmp_s, 'w') as f:
            f.write(f'{header}\tinclude "patch_syms.i"\n{pre}\n\torg\t${start:X}\n{body}')
        vasm(tmp_s, tmp_b, listing=tmp_l, inc=out)
        psyms.update({k: v for k, v in symbols(tmp_l).items() if k not in known})
        code = open(tmp_b, 'rb').read()
        if len(code) > end - start:
            sys.exit(f'{tag} patch {a}: {len(code)} bytes, only {end-start} available up to {b}')
        prog[start-load:start-load+len(code)] = code
        print(f'  {tag} patch {a:<14} ${start:05X}: {len(code):4d} of {end-start:4d} bytes')


def build_boot(out):
    """the enhanced bootblock: the original with src/boot_patches.s (the memory survey)"""
    os.makedirs(out, exist_ok=True)
    orig, lst = os.path.join(out, 'orig_boot.bin'), os.path.join(out, 'orig_boot.lst')
    vasm(os.path.join(ROOT, 'gng_boot.s'), orig, listing=lst, inc=out)
    boot = bytearray(open(orig, 'rb').read())
    if hashlib.sha1(boot).hexdigest() != BOOT_SHA1: sys.exit('gng_boot.s does not build the original')
    apply_patches(boot, os.path.join(SRC, 'boot_patches.s'), 0, '', symbols(lst), out, 'boot')
    assert len(boot) == 1024
    return boot


def build(name, raster=False, fps25=False):
    cfg = BUILDS[name]
    out = os.path.join(OUT, name + ('_25hz' if fps25 else '') + ('_raster' if raster else ''))
    os.makedirs(out, exist_ok=True)
    V = lambda *a, **k: vasm(*a, inc=out, **k)
    # 1. the original program and its labels
    orig, lst = os.path.join(out, 'orig_main.bin'), os.path.join(out, 'orig_main.lst')
    V(os.path.join(ROOT, cfg['src']), orig, listing=lst, defs=cfg['defs'])
    prog = bytearray(open(orig, 'rb').read())
    if hashlib.sha1(prog).hexdigest() != cfg['sha1']: sys.exit(f'{cfg["src"]} does not build the original')
    osyms = symbols(lst)
    for k, v in cfg['names'].items(): osyms[k] = v if isinstance(v, int) else osyms[v]
    write_syms(os.path.join(out, 'orig_syms.i'), osyms)
    # 2. the module
    mod, mlst = os.path.join(out, 'module.bin'), os.path.join(out, 'module.lst')
    V(os.path.join(SRC, 'module.s'), mod, listing=mlst,
      defs=cfg['defs'] + ((('RASTER_BUILD', 1),) if raster else ()))
    msyms = symbols(mlst, lambda n: n.startswith('Enh'))
    write_syms(os.path.join(out, 'module_syms.i'), msyms)
    org = int(re.search(r'^MODULE_ORG\s+E:([0-9A-F]+)$', open(mlst).read(), re.M).group(1), 16)
    mlen = os.path.getsize(mod)
    print(f'{name}: module.bin {mlen:,} bytes at ${org:X} (track {cfg["module_track"]})')
    # 3. the patches
    known = dict(osyms); known.update(msyms)
    header = (''.join(f'{k}\tequ\t{v}\n' for k, v in cfg['defs']) + f'\tinclude "{cfg["equates"]}"\n\tinclude "orig_syms.i"\n\tinclude "module_syms.i"\n'
              f'MODULE_ORG\tequ\t${org:X}\nMODULE_LEN\tequ\t{mlen}\nMODULE_TRACK\tequ\t{cfg["module_track"]}\n')
    apply_patches(prog, os.path.join(SRC, 'patches.s'), cfg['load'], header, known, out, name)
    if raster:
        apply_patches(prog, os.path.join(SRC, 'raster_patches.s'), cfg['load'], header, known, out, name + ' raster')
    if name == '512k' and not fps25:          # (the 1MB program already draws every frame)
        assert prog[0x6E76-cfg['load']:0x6E80-cfg['load']].hex() == '082e0000000767000314', 'odd-frame test'
        apply_patches(prog, os.path.join(SRC, 'fps50_patches.s'), cfg['load'], header, known, out, name + ' 50fps')
    main_out = os.path.join(out, 'main.bin')
    open(main_out, 'wb').write(prog)
    return main_out, mod


def mkdisk(adf, boot, files, adds):
    args = [sys.executable, os.path.join('tools', 'disk', 'mkdisk.py'), '-o', os.path.abspath(adf),
            '--boot', os.path.abspath(boot)]
    for k, v in files.items(): args += [f'--{k}', os.path.abspath(v)]
    for t, p in adds.items(): args += ['--add', f'{t}={os.path.abspath(p)}']
    r = subprocess.run(args, cwd=ROOT, capture_output=True, text=True)
    print(r.stdout + r.stderr, end='')
    if r.returncode: sys.exit('mkdisk failed')


def main(raster=False, fps25=False):
    os.makedirs(OUT, exist_ok=True)
    sfx = '_raster' if raster else ''
    if fps25:                                    # the 512K program at the original 25 fps: one image
        m512, mod512 = build('512k', raster, fps25=True)
        bootdir = os.path.join(OUT, 'boot')
        boot = build_boot(bootdir)
        for off, old, new in ((0x2C, '20380004', '70004e71'), (0x40, '203c00080000', '70004e714e71')):
            assert boot[off:off+len(old)//2].hex() == old
            boot[off:off+len(new)//2] = bytes.fromhex(new)
        boot_out = os.path.join(bootdir, 'boot_512k_only.bin')
        open(boot_out, 'wb').write(boot)
        adf = os.path.join(OUT, f'gng_enhanced_512k_25hz{sfx}.adf')
        mkdisk(adf, boot_out, {'main512': m512}, {BUILDS['512k']['module_track']: mod512})
        verify_image(adf, bytes(boot), {110: m512, BUILDS['512k']['module_track']: mod512})
        return
    built = {name: build(name, raster) for name in BUILDS}
    (m512, mod512), (m1mb, mod1mb) = built['512k'], built['1mb']
    bootdir = os.path.join(OUT, 'boot')
    boot = build_boot(bootdir)
    boot_out = os.path.join(bootdir, 'boot.bin')
    open(boot_out, 'wb').write(boot)
    # both programs; the bootblock chooses by memory, as the original
    adf = os.path.join(OUT, f'gng_enhanced{sfx}.adf')
    mkdisk(adf, boot_out, {'main512': m512, 'main1mb': m1mb},
           {BUILDS['512k']['module_track']: mod512, BUILDS['1mb']['module_track']: mod1mb})
    verify_image(adf, bytes(boot), {110: m512, 17: m1mb,
                 BUILDS['512k']['module_track']: mod512, BUILDS['1mb']['module_track']: mod1mb})
    # the 512K program only: load base always 0
    boot = bytearray(boot)
    for off, old, new in ((0x2C, '20380004', '70004e71'),               # move.l $4.w,d0 -> moveq #0,d0
                          (0x40, '203c00080000', '70004e714e71')):       # move.l #$80000,d0 -> moveq #0,d0
        assert boot[off:off+len(old)//2].hex() == old, f'bootblock ${off:X}'
        boot[off:off+len(new)//2] = bytes.fromhex(new)
    boot_out = os.path.join(bootdir, 'boot_512k_only.bin')
    open(boot_out, 'wb').write(boot)
    adf = os.path.join(OUT, f'gng_enhanced_512k{sfx}.adf')
    mkdisk(adf, boot_out, {'main512': m512}, {BUILDS['512k']['module_track']: mod512})
    verify_image(adf, bytes(boot), {110: m512, BUILDS['512k']['module_track']: mod512})


def verify_image(adf, boot, files):
    """decode the image again: the bootblock (and its checksum) and each given file (first
    track -> path) must read back exactly"""
    sys.path.insert(0, os.path.join(ROOT, 'tools', 'disk'))
    import mkdisk
    tracks = mkdisk.read_image(open(adf, 'rb').read())
    t0 = tracks[0][1]
    assert t0[:4] == boot[:4] and t0[8:1024] == boot[8:], 'bootblock'
    assert mkdisk.bootblock_checksum(t0[:1024]) == int.from_bytes(t0[4:8], 'big'), 'bootblock checksum'
    def read(t0, n):
        out = b''
        for t in range(t0, t0 + mkdisk.ntracks(n)):
            typ, raw, nb = tracks[t]
            r = mkdisk.decode_track(raw, nb)
            assert r and r[0] == t and r[2], f'track {t} does not decode'
            out += r[1]
        return out[:n]
    for t, path in files.items():
        data = open(path, 'rb').read()
        assert read(t, len(data)) == data, f'track {t}'
    print(f'{os.path.basename(adf)}: bootblock and the files at tracks {sorted(files)} decode back exactly')


if __name__ == '__main__':
    main(raster='--raster' in sys.argv, fps25='--fps25' in sys.argv)
