def file_records(S):
    """file id -> (destination expression, its value on 512K) from the program's FENTRY lines"""
    out = {}
    src = open(os.path.join(ENH, 'src', 'gng_game.s')).read()
    for m in re.finditer(r'^\tFENTRY\t([^,\n]+),[^,\n]+,(FID_\w+)(?:\+(\d))?', src, re.M):
        fid = S[m.group(2)] + int(m.group(3) or 0)
        expr = m.group(1).strip()
        val = int(expr, 0) if re.fullmatch(r'\d+', expr) else S.get(expr)
        out.setdefault(fid, (expr, val))
    return out


def disk(S, adf):
    d = open(adf, 'rb').read()
    magic, ver, count = struct.unpack_from('>4sHH', d, 0x400)
    entries = [struct.unpack_from('>LL', d, 0x410 + 8 * i) for i in range(count)]
    names = build_game.disk_files(os.path.join(build_game.OUT, 'game.bin'), 'sfx', 'music', 'relocs')
    fid_eq = {m.group(1): int(m.group(2)) for m in re.finditer(r'^(FID_\w+)\s+equ\s+(\d+)', open(os.path.join(ENH, 'src', 'gng_game.i')).read(), re.M)}
    S = dict(S, **fid_eq)
    fids = {v: k for k, v in fid_eq.items() if k != 'FID_COUNT'}
    rec = file_records(S)
    rows = []
    for i, (off, ln) in enumerate(entries):
        key = fids.get(i) or next(f'{k}+{i - S[k]}' for k in ('FID_LEVEL0', 'FID_TABLES0') if S[k] <= i < S[k] + 7)
        base = key.split('+')[0]
        what, by, when = FILES[base]
        if base in ('FID_LEVEL0', 'FID_TABLES0'):
            n = i - S[base]
            what = what.replace("a level's", f"stage {n + 1}'s (level {n})")
        dest = rec.get(i, ('', None))
        dtxt = {0: '`$80` (bootblock)', 1: '`$60000` (bootblock)'}.get(i, f'`{dest[0]}`' + (f' ({h(dest[1])})' if dest[1] else ''))
        if base == 'FID_RELOCS': dtxt = 'after the moved program'
        t0, t1 = off // TRACK, (off + ln - 1) // TRACK
        rows.append(f'| {i} | `{key}` | {what} | {h(off)} | {kb(ln)} | {t0}-{t1} | {dtxt} | {by}: {when} |')
    end = entries[-1][0] + entries[-1][1]
    return magic.decode(), ver, count, rows, end, len(d)


def write_disk(S):
    adf = os.path.join(build_game.OUT, '..', 'gng_game.adf')
    magic, ver, count, rows, end, size = disk(S, adf)
    text = HEAD + f"""
# The disk

`enhanced/build/gng_game.adf` (`build_game.py`): an ordinary 880K AmigaDOS-format disk image -
80 cylinders x 2 heads x 11 sectors of 512 bytes ({kb(size)} bytes), the sectors in the standard
AmigaDOS MFM format with the `$4489` sync - with no filesystem (Workbench shows it as NDOS). Any
emulator or drive reads it; nothing on it is copy-protected. A *track* below is one side of a
cylinder, 5,632 bytes, as the byteloader counts them (disk offset / 5,632).

| Disk offset | Bytes | |
|---|---:|---|
| `$00000` | 1,024 | the bootblock (`src/boot_4489.s`): `'DOS',0`, checksum, root block 880, then the code |
| `$00400` | {16 + 8 * count} | the file table (`FT_OFFSET`) |
| `$00600` | {kb(end - 0x600)} | the files, one after another, in file id order |
| {h(end)} | {kb(size - end)} | free |

**The file table** (at `FT_OFFSET` = `$400`; `gng_game.i` `FT_*`, written by `build_game.py`,
read by the bootblock and, once, by the game's `LoadFile` into `FileDir`):

| Offset | Size | |
|---|---|---|
| 0 | 4 | `'{magic}'` |
| 4 | 2 | version ({ver}) |
| 6 | 2 | number of files ({count}) |
| 8 | 8 | (zero) |
| 16 + 8 x id | 4 | the file's offset on the disk |
| 20 + 8 x id | 4 | its length in bytes |

A file is named by its id (`FID_` in `gng_game.i`; the order is `disk_files()` in
`build_game.py`). In the program a file record (`FENTRY` macro) is the load address, the length
and the file id; `build_game.py` checks every record's length against its file.

**The files** (this build):

| Id | Name | Contents | Disk offset | Bytes | Tracks | Loaded to (512K) | Loaded by: when |
|---|---|---|---|---:|---|---|---|
""" + '\n'.join(rows) + f"""

The formats of the files are in `FORMATS.md`. A level start reads only its own sets from the
enemy graphics file (`LoadEnemySets`: pieces of the file, `LoadOffset`), and on an expanded
machine the files read again and again come from the file cache after their first load
(`FEATURES.md`, *Loading*).

**Reading the disk.** The bootblock and the game both read files with the
[4489_byteloader](https://github.com/MarkyTurtle/4489_byteloader) (`src/byteloader.i`): a file is
an offset and a length, the loader reads each track it touches by disk DMA into an MFM buffer
(`$1760` words), decodes it with the CPU, checks the sectors' checksums and copies out the bytes
asked for (a track is read again until its checksums are right). It times itself on `VHPOSR` and
leaves the interrupts, CIA timers, blitter and copper alone; it uses every register, `a6`
included (the game's interrupt handlers set `a6` themselves: `IrqLevel1` / `IrqLevel3`).

**Booting** (`src/boot_4489.s`). Kickstart loads the bootblock and calls it with `a6` = ExecBase:
1. `MemDetect` walks exec's memory list and writes the machine description (`MACHINE_INFO`,
   `$7FB00`; see `FORMATS.md`) - chip RAM, slow RAM, fast RAM, PAL / NTSC, CPU - and the drive
   it was booted from: it opens `trackdisk.device`'s units 3 to 0 (an IORequest on the stack)
   until one is the boot IORequest's unit (`IO_UNIT`), DF0 if none is. Kickstart 1.3 boots only
   from DF0; 2.0 and later from any drive (the early startup menu). Every load reads that drive,
   in the bootblock and in the game (`LoadDisk`: `BootDrive`);
2. it takes the machine over (interrupts and DMA off, the original bootblock's fade);
3. it copies its loader to `$7FB24` and runs it there: the file table to `$7F000` (MFM buffer at
   `$7C000`), the loading picture (file 1) to `$60000`, shown with its own copper lists (the
   second one, for the other field, made from the first after the loader) and level 3 interrupt
   (HAM, interlaced), then the program (file 0) to `$80`;
4. `$4.w` = `$80`, and it enters the program at `$A0` (`ProgramEntry`), as the original did.
A failed read is tried again; after 8 failures COLOR00 turns red while it keeps trying.
"""
    open(os.path.join(DOCS, 'DISK.md'), 'w').write(text)


def table(rows):
    """rows of (start, end, name, contents) -> markdown lines, sorted, with gaps shown"""
    out = ['| From | To | Bytes | Name | Contents |', '|---|---|---:|---|---|']
    rows = sorted(rows)
    for k, (a, b, name, what) in enumerate(rows):
        if k and a > rows[k - 1][1]:
            out.append(f'| {h(rows[k - 1][1])} | {h(a)} | {kb(a - rows[k - 1][1])} | | (not used) |')
        out.append(f'| {h(a)} | {h(b)} | {kb(b - a)} | {name} | {what} |')
    return out


