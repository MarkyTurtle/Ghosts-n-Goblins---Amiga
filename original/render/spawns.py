"""Spawn maps: for each level, the map zone of every cell and the spawners each zone starts,
drawn over render/out/level<n>.png (-> level<n>_spawns.png), plus docs/SPAWNS.md."""
import struct, sys, os
from PIL import Image, ImageDraw
G=open('../bin/main_512k.bin','rb').read(); B=0x80
rb=lambda a:G[a-B]; rw=lambda a:struct.unpack('>h',G[a-B:a-B+2])[0]; ruw=lambda a:struct.unpack('>H',G[a-B:a-B+2])[0]
WM=0x44D6; MZT=0x4637; ZS=0x4798; SS=0x48D5
NAMES={0:'Woody Pig',1:'Crow',2:'Petite Devil',3:'Flying Knight',4:'Blue Killer',5:'Red Arremer',6:'Satan',7:'Magician',8:'Unicorn',9:'Skeleton',10:'Big Man',11:'Zombie',12:'Dragon',13:'Astaroth',14:'Fire',15:'Princess',16:'type 16'}
LEVELNAME=['0 graveyard / forest','1','2','3','4','5','6 throne room']
quota=[list(G[0x43F6-B+16*l:0x43F6-B+16*l+16]) for l in range(7)]
ZONEFLAGS=list(G[0x7BC8-B:0x7BC8-B+16])
def zone_list(z):
    la=ZS+z+rb(ZS+z); n=rb(la); out=[]
    for k in range(n):
        b1,b2=rb(la+1+2*k),rb(la+2+2*k); out.append((b1>>4,((b1&15)<<4)|(b2&15),b2>>4))
    return out
def script(t,s):
    ta=SS+t+rb(SS+t); sa=ta+2*s; sp=sa+rw(sa); n=ruw(sp)
    return [(rw(sp+2+6*k),rw(sp+4+6*k),rb(sp+6+6*k),rb(sp+7+6*k)) for k in range(n)]
md=['# Enemy spawns','',
 'Generated by `render/spawns.py` from the spawn tables (`MapZoneTable`, `ZoneSpawners`,',
 '`SpawnScripts` in `gng_main.s`). See `UpdateMapZone` and `UpdateSpawners` for how they run.','',
 '* Every 256 x 256 map cell has a **zone** number. When the cell under the camera changes zone,',
 '  `UpdateMapZone` stops the running spawners and starts the new zone\'s list.',
 '* Each **spawner** belongs to one enemy type and runs a **script** of entries: position, enemy',
 '  parameter, and the delay in frames before the next entry. Positions are relative to the camera',
 '  (the bottom-left corner of the view, Y up; zombies get another 128 px in X) unless the spawner',
 '  has *world coords*, in which case they are world pixels. A script repeats unless it *runs once*.',
 '  World-coordinate spawn points are circled in red on `render/out/level<n>_spawns.png`.',
 '* A spawn also needs a free enemy slot and that type\'s **spawn quota** (`LevelSpawnQuota`, below)',
 '  to be above 0; most enemies give their quota back when they leave.',
 f'* Types with ZoneFlags = 0 ({", ".join(NAMES[t] for t in range(16) if ZONEFLAGS[t]==0)})',
 '  only start in a zone further on than any reached before, and keep running across zone changes.',
 '* The Magician has no zone spawner: shooting a gravestone 15 times starts it (`ShotsVsScenery`).','']
os.makedirs('out',exist_ok=True)
for lv in range(7):
    x0c,x1c,y1c,y0c=G[0x4466-B+4*lv:0x4466-B+4*lv+4]
    origin=0x44BA+rw(0x44BA+2*lv); off=origin-WM; orow,ocol=divmod(off,32)
    cw=x1c-x0c+1; ch=y1c-y0c+1
    im=Image.open(f'out/level{lv}.png').convert('RGB'); d=ImageDraw.Draw(im)
    zones=[]
    md+=[f'## Level {LEVELNAME[lv]}','',
         'Spawn quota per type: '+', '.join(f'{NAMES[t]} {quota[lv][t]}' for t in range(16) if quota[lv][t]),'',
         'Zone of each cell (top row first):','','```']
    for rr in reversed(range(ch)):
        row=[]
        for cc in range(cw):
            o=off+rr*32+cc
            z=rb(MZT+o) if o<353 else None
            row.append(f'{z:4d}' if z is not None else '   -')
            if z is not None and z not in zones: zones.append(z)
            X=cc*256; Y=(ch-1-rr)*256
            d.rectangle([X,Y,X+255,Y+255],outline=(255,255,255))
            lst=zone_list(z) if z is not None else []
            txt=f'zone {z}'+''.join(f'\n{NAMES[t]} #{s}' for t,s,f in lst)
            d.multiline_text((X+4,Y+4),txt,fill=(255,255,0))
        md.append(''.join(row))
    md+=['```','']
    md+=['| Zone | Spawners |','|---|---|']
    for z in sorted(zones):
        lst=zone_list(z)
        if not lst: continue
        md.append(f'| {z} | '+'<br>'.join(f'{NAMES[t]} script {s}'+(' (world coords' if f&1 else '')+(', runs once' if f&3==3 else (' (runs once' if f&2 else ''))+(')' if f&3 else '') for t,s,f in lst)+' |')
    md+=['']
    seen=set()
    for z in sorted(zones):
        for t,s,f in zone_list(z):
            if (t,s) in seen: continue
            seen.add((t,s)); es=script(t,s)
            md.append(f'* **{NAMES[t]} script {s}** ({"world" if f&1 else "camera"} coordinates): '+'; '.join(f'({x}, {y}) p{p} +{dl}' for x,y,p,dl in es))
            if f&1:
                for x,y,p,dl in es:
                    X=x-ocol*256; Y=ch*256-(y-orow*256)
                    if 0<=X<cw*256 and 0<=Y<ch*256:
                        d.ellipse([X-6,Y-6,X+6,Y+6],outline=(255,64,64),width=2); d.text((X+8,Y-6),f'{NAMES[t]}',fill=(255,96,96))
    md+=['']
    im.save(f'out/level{lv}_spawns.png')
open('../docs/SPAWNS.md','w').write('\n'.join(md)+'\n')
print('ok')
