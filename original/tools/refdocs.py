"""Generate the reference pages from the annotation database and the generated source:
  ../docs/GLOBALS.md  every global (offset from a6 = GLOBALS), the memory map, the object
                      slot layout and the per-type fields
  ../docs/XREF.md     for every global and every named routine or table: the routines that use it
Run from tools/ after gen.py:   python3 refdocs.py"""
import os, re, sys
sys.path.insert(0, '.')
import anno_db as A

out = os.environ.get('DOCS', os.path.join('..', 'docs'))
os.makedirs(out, exist_ok=True)
src = open('gng_main.s').read().split('\n')

def esc(t): return (t or '').replace('|', '\\|').replace('\n', ' ')

# ---------------------------------------------------------------- GLOBALS.md
ranges = dict(A.VAR_RANGES)
L = ['# Globals, memory map and object layouts', '',
     'Generated by `tools/refdocs.py` from the annotation database. Offsets are from `a6`, which points',
     'at `GLOBALS` (`$1898C`) for the whole game (512K build; the 1MB build inserts `g_BaseAddr` at `+2`,',
     'so every offset from `+2` on is 4 higher there).', '',
     '## Globals', '', '| Offset | Name | Size | Notes |', '|---|---|---|---|']
offs = sorted(A.VARS)
for i, o in enumerate(offs):
    n, c = A.VARS[o]
    size = ranges.get(o)
    if size is None and i+1 < len(offs): size = offs[i+1]-o if offs[i+1]-o <= 4 else ''
    L.append(f'| `${o:03X}` | `{n}` | {size} | {esc(c)} |')
L += ['', '## Memory map (512K build)', '', '| Address | Name | Notes |', '|---|---|---|']
for a in sorted(A.MEM):
    L.append(f'| `${a:05X}` | `{A.MEM[a]}` | {esc(A.MEMC.get(a, ""))} |')
L += ['', '## Object slots', '',
      'Enemies (`g_Enemies`, 40 x `$3C`), enemy shots (`g_EnemyShots`, 6 x `$1C`), items (`g_Items`, 30 x `$1C`),',
      "Arthur's shots (`g_Shots`, 4 x `$26`) and special objects (`g_SpecialObjs`, 2 x `$20`) share this layout:", '',
      '| Offset | Field | Notes |', '|---|---|---|']
for o in sorted(A.OBJ_FIELDS):
    n, c = A.OBJ_FIELDS[o]; L.append(f'| `+${o:02X}` | `{n}` | {esc(c)} |')
L += ['', '## Fields by object type', '', 'Offsets `$1C` on are used differently by each type (names used in the source):', '']
groups = {}
for lo, hi, fm in A.TYPE_FIELDS:
    groups.setdefault((lo, hi), {}).update(fm)
for (lo, hi), fm in sorted(groups.items()):
    owner = A.NAMES.get(lo, f'${lo:05X}')
    L += [f'### {owner} (`${lo:05X}`-`${hi:05X}`)', '', '| Offset | Field | Notes |', '|---|---|---|']
    for o in sorted(fm):
        n, c = fm[o]; L.append(f'| `+${o:02X}` | `{n}` | {esc(c)} |')
    L.append('')
open(os.path.join(out, 'GLOBALS.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(L)+'\n')

# ---------------------------------------------------------------- XREF.md
named = {v for v in A.NAMES.values()}
varnames = {v[0] for v in A.VARS.values()}
routine = None; uses = {}
lab_re = re.compile(r'^([A-Za-z_]\w*):')
tok_re = re.compile(r'\b([A-Za-z_]\w*)\b')
for l in src:
    m = lab_re.match(l)
    if m:
        n = m.group(1)
        if not re.match(r'(l|jtab|sub|dat)_', n): routine = n
        continue
    if not routine or not l.startswith('        ') or '; 0' not in l: continue
    code = l.split(';')[0]
    for t in set(tok_re.findall(code)):
        if t == routine: continue
        if t in varnames or (t in named and not re.match(r'(l|jtab|sub|dat)_', t)):
            uses.setdefault(t, set()).add(routine)
L = ['# Cross-reference', '', 'Generated by `tools/refdocs.py`: for each global and each named routine or table, the',
     'routines (top-level labels) whose code refers to it in `gng_main.s` (512K build).', '',
     '## Globals', '', '| Global | Used by |', '|---|---|']
for o in sorted(A.VARS):
    n = A.VARS[o][0]
    if n in uses: L.append(f'| `{n}` | {", ".join(sorted(uses[n]))} |')
L += ['', '## Routines and tables', '', '| Name | Used by |', '|---|---|']
for n in sorted(uses, key=str.lower):
    if n in varnames: continue
    L.append(f'| `{n}` | {", ".join(sorted(uses[n]))} |')
open(os.path.join(out, 'XREF.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(L)+'\n')
print('GLOBALS.md', len(A.VARS), 'globals;', 'XREF.md', len(uses), 'symbols')
